#!/usr/bin/env bash
set -euo pipefail

PROJECT_DIR="$(pwd)"

echo "=== Creating isolated renv in ${PROJECT_DIR} ==="


# --------------------------------------------------
# Modules
# --------------------------------------------------
module purge
module load prgenv/gnu
module load netcdf4
module load ecmwf-toolbox/2025.04.0.0
module load R/4.4.3

# --------------------------------------------------
# Hard isolation from HOME
# --------------------------------------------------
GCC_LIB=/usr/local/apps/gcc/13.1.0/lib64
export LD_LIBRARY_PATH="${GCC_LIB}:${LD_LIBRARY_PATH:-}"

unset R_ENVIRON_USER
unset R_PROFILE
unset R_PROFILE_USER
unset R_LIBS
unset R_LIBS_USER

export R_ENVIRON_USER=/dev/null
export R_PROFILE_USER="$(pwd)/.Rprofile"

# --------------------------------------------------
# renv paths (project-local)
# --------------------------------------------------
export RENV_PROJECT="$(pwd)"
export RENV_CONFIG_USE_CACHE=FALSE
export RENV_PROJECT_SANDBOX=TRUE
export RENV_PATHS_ROOT="$(pwd)/renv"
export RENV_PATHS_LIBRARY="$(pwd)/renv/library"
export RENV_PATHS_CACHE="$(pwd)/renv/cache"

# If private GitHub repositories are used, pass a valid GITHUB_PAT in the
# environment when starting this script; never replace it with a placeholder.

# --------------------------------------------------
# Bootstrap renv
# --------------------------------------------------
BOOTSTRAP_LIB="$(pwd)/.bootstrap_lib"
mkdir -p "$BOOTSTRAP_LIB"

if [ ! -d "$BOOTSTRAP_LIB/renv" ]; then
    echo "=== Installing renv into .bootstrap_lib ==="
    Rscript --vanilla - <<EOF
.libPaths("$BOOTSTRAP_LIB")
options(repos = c(CRAN = "https://cloud.r-project.org"))
install.packages("renv", lib="$BOOTSTRAP_LIB")
EOF
fi

# --------------------------------------------------
# Run project setup WITH bootstrap lib visible
# --------------------------------------------------
export ARROW_R_ALLOW_CPP17=true
export ARROW_S3=OFF
export ARROW_GCS=OFF
export ARROW_MIMALLOC=OFF
export ARROW_DEPENDENCY_SOURCE=BUNDLED
export LIBARROW_MINIMAL=true
export ARROW_R_DEV=true   # shows the full build log in the output
export NOT_CRAN=true
Rscript --vanilla - <<EOF
.libPaths(c("$BOOTSTRAP_LIB", .libPaths()))
source("atos_renv.R")
EOF

# --------------------------------------------------
# Write final project .Rprofile (absolute-path activation)
# --------------------------------------------------
echo "=== Writing project .Rprofile ==="

cat > "${PROJECT_DIR}/.Rprofile" <<EOF
## Project-local .Rprofile for renv
## Generated by isolated_install.sh

Sys.setenv(
  R_ENVIRON_USER = "/dev/null",
  R_PROFILE_USER = "/dev/null"
)

project <- Sys.getenv("RENV_PROJECT")

if (nzchar(project)) {
  activate <- file.path(project, "renv", "activate.R")
  if (file.exists(activate)) {
    source(activate)
  } else {
    stop("renv activation script not found at: ", activate)
  }
} else {
  warning("RENV_PROJECT not set; renv not activated")
}
EOF

echo "=== renv installation and configuration complete ==="

# --------------------------------------------------
# Write Setenv activation script
# --------------------------------------------------
echo "=== Writing RENV/Setenv ==="

cat > "${PROJECT_DIR}/Setenv" <<EOF
#!/usr/bin/env bash

export PATH="\$HOME/.local/bin:\$PATH"
module purge
module load prgenv/gnu
module load R/4.4.3
module load python3/3.10.10-01
module load ecflow
module load netcdf4
module load ecmwf-toolbox/2025.04.0.0

export LD_LIBRARY_PATH="/usr/local/apps/gcc/13.1.0/lib64:${LD_LIBRARY_PATH:-}"
export R_ENVIRON_USER=/dev/null
export R_PROFILE_USER=${PROJECT_DIR}/.Rprofile
export RENV_PROJECT=${PROJECT_DIR}
export RENV_CONFIG_USE_CACHE=FALSE

EOF

chmod +x "${PROJECT_DIR}/Setenv"
